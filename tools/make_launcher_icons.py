"""Generate every launcher-icon asset from mascot_header.png.

WHY A GENERATOR AND NOT FIVE HAND-EXPORTS
-----------------------------------------
The mascot is a FULL-BLEED circular badge: the brown ring (#793000) and the white
ring inside it sit on the outermost pixels (measured: the opaque circle spans
x=1..238 of a 240px canvas). An adaptive icon masks a 108dp canvas down to a
~72dp viewport, so a full-bleed foreground loses the rings entirely. The fix is
to shrink the art into the safe zone and let a cream background fill the rest —
which is a per-density arithmetic problem, not a drawing problem.

OUTPUTS
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher.png          48/72/96/144/192
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher_round.png    same sizes
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher_foreground.png  108/162/216/324/432
                                                      art at 72/108/144/216/288
  mipmap-anydpi-v26/ic_launcher.xml                   background @color/ic_launcher_background
  mipmap-anydpi-v26/ic_launcher_round.xml

All resampling is LANCZOS. The foreground is composed onto a transparent canvas,
so the cream comes from the <background> layer and stays correct under every
mask shape (circle, squircle, rounded square).
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]          # momompurin-live-manager
RES = ROOT / "app" / "src" / "main" / "res"
SRC = Path(r"C:\Users\Gabri\Desktop\Software Project (SOFTENG-HCI)\mascot_header.png")

DENSITIES = [("mdpi", 1.0), ("hdpi", 1.5), ("xhdpi", 2.0), ("xxhdpi", 3.0), ("xxxhdpi", 4.0)]

# Legacy launcher icon: 48dp.
LEGACY_DP = 48
# Adaptive icon: 108dp canvas, art at 66.67% (the task's safe-zone figure).
CANVAS_DP = 108
ART_FRACTION = 72 / 108

BACKGROUND = "#FFF8E7"   # Momompurin warm cream

ADAPTIVE_TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!--
  Adaptive launcher icon (Android 8+).

  The mascot art is a full-bleed circular badge, so a full-bleed foreground would
  have its brown (#793000) and white rings cut off by the ~72dp mask viewport.
  The foreground PNG therefore draws the badge at {pct}% of the 108dp canvas,
  centred, on a TRANSPARENT field; the cream background fills the rest and shows
  through whatever the launcher's mask shape is (circle, squircle, rounded
  square). Generated by tools/make_launcher_icons.py - do not hand-edit.
-->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""


def resample(im: Image.Image, size: int) -> Image.Image:
    """LANCZOS downscale to an exact square. `size` is the edge in px."""
    return im.resize((size, size), Image.Resampling.LANCZOS)


def main() -> None:
    src = Image.open(SRC).convert("RGBA")
    if src.size != (240, 240):
        raise SystemExit(f"unexpected source size {src.size}; expected 240x240")
    # Sanity: the art must be a circle that reaches the canvas edge, or the
    # "shrink into the safe zone" reasoning does not apply.
    bbox = src.getbbox()
    if bbox != (0, 0, 240, 240):
        print(f"  note: alpha bbox is {bbox}, not the full canvas")

    made: list[str] = []

    for name, scale in DENSITIES:
        out = RES / f"mipmap-{name}"
        out.mkdir(parents=True, exist_ok=True)

        # ---- legacy + round: the art exactly as drawn (it is already a disc,
        # so the transparent corners do the "round" masking on old launchers).
        legacy_px = round(LEGACY_DP * scale)
        icon = resample(src, legacy_px)
        icon.save(out / "ic_launcher.png", optimize=True)
        icon.save(out / "ic_launcher_round.png", optimize=True)
        made.append(f"mipmap-{name}/ic_launcher.png {legacy_px}x{legacy_px}")
        made.append(f"mipmap-{name}/ic_launcher_round.png {legacy_px}x{legacy_px}")

        # ---- adaptive foreground: 108dp canvas, art at ART_FRACTION, centred.
        canvas_px = round(CANVAS_DP * scale)
        art_px = round(canvas_px * ART_FRACTION)
        canvas = Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
        art = resample(src, art_px)
        offset = (canvas_px - art_px) // 2
        canvas.alpha_composite(art, (offset, offset))
        canvas.save(out / "ic_launcher_foreground.png", optimize=True)
        made.append(
            f"mipmap-{name}/ic_launcher_foreground.png {canvas_px}x{canvas_px} "
            f"(art {art_px} at +{offset})"
        )

    # ---- the two adaptive descriptors
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    pct = round(ART_FRACTION * 100)
    for fname in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / fname).write_text(
            ADAPTIVE_TEMPLATE.format(pct=pct), encoding="utf-8"
        )
        made.append(f"mipmap-anydpi-v26/{fname}")

    for line in made:
        print("  " + line)
    print(f"\n{len(made)} assets written; background {BACKGROUND}")


if __name__ == "__main__":
    sys.exit(main())
